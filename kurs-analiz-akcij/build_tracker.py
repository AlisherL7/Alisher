def setup(ws, title, legend, headers, widths, freeze="A3"):
    ws["A1"] = title
    ws["A1"].font = TITLE
    ws["A2"] = legend            # временно, перезапишем строкой заголовков ниже
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=2, column=i, value=h)
        c.font = HEAD; c.fill = HEADFILL; c.border = BOX
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    ws.row_dimensions[2].height = 34
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    last = get_column_letter(len(headers))
    ws.auto_filter.ref = f"A2:{last}2"
    return last

def dv(ws, formula1, cells, prompt=None):
    d = DataValidation(type="list", formula1=formula1, allow_blank=True, showDropDown=False)
    ws.add_data_validation(d)
    for rng in cells:
        d.add(rng)
    return d

